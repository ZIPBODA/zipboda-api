import { addressKeyOf, nameKeyOf } from './complex-keys.js';

describe('단지 판별 키', () => {
  it.each([
    // 원천마다 붙는 괄호 참고 항목·건물 이름을 버린다
    ['서울특별시 강남구 논현로12길 23-5(개포동,T&K개포) T&K개포', '서울특별시 강남구 논현로12길 23-5'],
    ['서울특별시 중랑구 동일로149가길 21(묵동) 묵동 245-39', '서울특별시 중랑구 동일로149가길 21'],
    // LH 연계시스템마다 다르게 적은 같은 단지(공릉동 240-1)가 같은 키가 된다
    ['서울특별시 노원구 공릉동 240-1', '서울특별시 노원구 공릉동 240-1'],
    ['서울특별시 노원구 공릉동 240-1 일원 (서울공릉 신혼희망타운)', '서울특별시 노원구 공릉동 240-1'],
    // 호별 주소의 동·호를 버려 같은 건물의 호들이 한 단지가 된다
    ['경기도 부천시 소사구 소사로148번길 58-9(소사본동) 한결주택 101동/소사구', '경기도 부천시 소사구 소사로148번길 58-9'],
    ['  서울특별시   송파구 가락로11길  8-19 ', '서울특별시 송파구 가락로11길 8-19'],
    // 도로명 상세주소는 쉼표 뒤에 동·호가 온다
    ['서울특별시 강남구 테헤란로 152, 101동 1203호(역삼동)', '서울특별시 강남구 테헤란로 152'],
    ['서울특별시 강남구 테헤란로 152,101동', '서울특별시 강남구 테헤란로 152'],
    // 지번 표기 차이('번지'·'산 12')는 같은 키가 된다
    ['서울특별시 노원구 공릉동 240-1번지', '서울특별시 노원구 공릉동 240-1'],
    ['인천광역시 서구 가정동 산12', '인천광역시 서구 가정동 산12'],
    ['인천광역시 서구 가정동 산 12', '인천광역시 서구 가정동 산12'],
    ['인천광역시 서구 가정동 산 12번지', '인천광역시 서구 가정동 산12'],
  ])('주소 %s → %s', (address, expected) => {
    expect(addressKeyOf(address)).toBe(expected);
  });

  it.each(['경기도 화성시 동탄2택지개발지구 내 A83블록', '서울특별시 강서구', ''])(
    '건물 번호가 없는 주소 %j는 판별하지 않는다',
    (address) => {
      expect(addressKeyOf(address)).toBeNull();
    },
  );

  it('이름은 공백만 정리하고 앞부분 일치는 다른 이름으로 본다', () => {
    expect(nameKeyOf('  강서  화곡동 ')).toBe('강서 화곡동');
    expect(nameKeyOf('강서화곡동')).not.toBe(nameKeyOf('강서화곡동(더샵)'));
  });
});
